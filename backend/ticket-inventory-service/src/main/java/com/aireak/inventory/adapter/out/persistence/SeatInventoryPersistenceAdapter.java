package com.aireak.inventory.adapter.out.persistence;

import com.aireak.common.cache.LocalStringCache;
import com.aireak.inventory.application.port.out.SeatInventoryRepository;
import com.aireak.inventory.domain.model.Seat;
import com.aireak.inventory.domain.model.SeatCode;
import com.aireak.inventory.domain.model.SeatInventory;
import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Component;

import java.time.Duration;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.stream.Collectors;

/**
 * Persistence adapter: maps SeatInventory aggregate ↔ JPA entities.
 *
 * <p>Mapping strategy:
 * <ul>
 *   <li>SeatInventory → SeatInventoryJpaEntity (1:1 by showtimeId)</li>
 *   <li>Seat → SeatJpaEntity (1:N owned by SeatInventory)</li>
 * </ul>
 */
@Component
@RequiredArgsConstructor
public class SeatInventoryPersistenceAdapter implements SeatInventoryRepository {

    // Local (per-JVM, NOT shared across pods) cache of CONFIRMED-existing showtimeIds only — a
    // seat inventory row, once generated by SeatMapGenerationService, is never deleted (no match
    // cancellation or admin action removes it), so "exists=true" is a permanent fact safe to
    // cache. Never caches "false": a showtime whose inventory hasn't been generated yet must
    // always re-check Postgres, since that state is genuinely about to change (and a false
    // negative here just costs a redundant DB read, never an incorrect allow). This runs inside
    // SeatInventoryService's per-showtime Redisson lock on every reserve/hold call — the hottest
    // existence check in the platform — so skipping Postgres here directly shortens lock hold
    // time under contention.
    //
    // AFTER_ACCESS, not AFTER_WRITE: a showtime on sale gets reserve/hold calls continuously, so
    // an actively-selling showtime should never fall out of cache and pay a redundant DB read —
    // only a showtime nobody has touched in LOCAL_CACHE_TTL (sale paused, event long past) is
    // freed. Key space is naturally tiny (one entry per scheduled showtime, not per
    // booking/user), so a generous size/TTL costs nothing either way.
    private static final long LOCAL_CACHE_MAX_SIZE = 5_000;
    private static final Duration LOCAL_CACHE_TTL = Duration.ofHours(6);

    private final LocalStringCache existingShowtimeCache =
            new LocalStringCache(LOCAL_CACHE_MAX_SIZE, LOCAL_CACHE_TTL, LocalStringCache.ExpiryPolicy.AFTER_ACCESS);

    private final SeatInventoryJpaRepository jpaRepository;
    private final SeatJpaRepository seatJpaRepository;

    /**
     * Writes a whole seat map. In practice only {@code SeatMapGenerationService} calls this, and
     * only for a showtime that does not have one yet (it returns early otherwise), so the
     * existing-row branch below no longer runs: selling seats goes through {@link #saveSeats},
     * which never loads or rewrites the map.
     *
     * <p>That branch is kept rather than deleted because dropping it would quietly make this
     * method wrong for an existing showtime instead of merely unused: {@link #toJpaEntity} builds
     * detached seats with no id, so merging those over a map that already has rows would insert
     * duplicates and break {@code uk_seats_showtime_code}. Mutating the managed rows in place is
     * what keeps re-saving a populated showtime correct if anything ever needs to.
     */
    @Override
    public void save(SeatInventory seatInventory) {
        SeatInventoryJpaEntity entity = jpaRepository.findByShowtimeId(seatInventory.getShowtimeId())
                .map(existing -> updateSeats(existing, seatInventory))
                .orElseGet(() -> toJpaEntity(seatInventory));
        jpaRepository.save(entity);
    }

    private SeatInventoryJpaEntity updateSeats(SeatInventoryJpaEntity entity, SeatInventory agg) {
        Map<String, SeatJpaEntity> bySeatCode = entity.getSeats().stream()
                .collect(Collectors.toMap(SeatJpaEntity::getSeatCode, s -> s));
        agg.getSeats().forEach(seat -> {
            SeatJpaEntity existing = bySeatCode.get(seat.getSeatCode().value());
            if (existing != null) {
                existing.setStatus(seat.getStatus());
                existing.setReservedByBookingId(seat.getReservedByBookingId());
            }
        });
        return entity;
    }

    @Override
    public Optional<SeatInventory> findByShowtimeId(String showtimeId) {
        return jpaRepository.findByShowtimeId(showtimeId).map(this::toDomain);
    }

    @Override
    public boolean existsByShowtimeId(String showtimeId) {
        if (existingShowtimeCache.getIfPresent(showtimeId).isPresent()) {
            return true;
        }
        boolean exists = jpaRepository.existsByShowtimeId(showtimeId);
        if (exists) {
            existingShowtimeCache.put(showtimeId, "1");
        }
        return exists;
    }

    @Override
    public Optional<SeatInventory> findByShowtimeIdWithSeats(String showtimeId, List<SeatCode> seatCodes) {
        // Existence is checked separately (and off the local cache) rather than inferred from an
        // empty seat list: "this showtime has no inventory" and "none of these seat codes exist"
        // are different answers, and only the first should read as not-found to the caller.
        if (!existsByShowtimeId(showtimeId)) {
            return Optional.empty();
        }
        return Optional.of(SeatInventory.reconstitute(showtimeId, findSeatsByCodes(showtimeId, seatCodes)));
    }

    @Override
    public void saveSeats(SeatInventory seatInventory) {
        Map<String, Seat> bySeatCode = seatInventory.getSeats().stream()
                .collect(Collectors.toMap(seat -> seat.getSeatCode().value(), seat -> seat));
        if (bySeatCode.isEmpty()) {
            return;
        }
        List<SeatJpaEntity> rows = seatJpaRepository.findByShowtimeIdAndSeatCodeIn(
                seatInventory.getShowtimeId(), List.copyOf(bySeatCode.keySet()));
        rows.forEach(row -> {
            Seat seat = bySeatCode.get(row.getSeatCode());
            row.setStatus(seat.getStatus());
            row.setReservedByBookingId(seat.getReservedByBookingId());
        });
        seatJpaRepository.saveAll(rows);
    }

    @Override
    public List<Seat> findSeatsByCodes(String showtimeId, List<SeatCode> seatCodes) {
        List<String> codes = seatCodes.stream().map(SeatCode::value).toList();
        return seatJpaRepository.findByShowtimeIdAndSeatCodeIn(showtimeId, codes)
                .stream()
                .map(s -> new Seat(
                        new SeatCode(s.getSeatCode()),
                        s.getStatus(),
                        s.getReservedByBookingId(),
                        s.getTier(),
                        s.getPrice()))
                .toList();
    }

    // ----------------------------------------------------------------
    // Domain → JPA
    // ----------------------------------------------------------------

    private SeatInventoryJpaEntity toJpaEntity(SeatInventory agg) {
        List<SeatJpaEntity> seatEntities = agg.getSeats().stream()
                .map(s -> SeatJpaEntity.builder()
                        .showtimeId(agg.getShowtimeId())
                        .seatCode(s.getSeatCode().value())
                        .status(s.getStatus())
                        .reservedByBookingId(s.getReservedByBookingId())
                        .tier(s.getTier())
                        .price(s.getPrice())
                        .build())
                .collect(Collectors.toList());

        SeatInventoryJpaEntity entity = SeatInventoryJpaEntity.builder()
                .showtimeId(agg.getShowtimeId())
                .build();
        entity.getSeats().clear();
        entity.getSeats().addAll(seatEntities);
        return entity;
    }

    // ----------------------------------------------------------------
    // JPA → Domain (reconstitute)
    // ----------------------------------------------------------------

    private SeatInventory toDomain(SeatInventoryJpaEntity entity) {
        List<Seat> seats = entity.getSeats().stream()
                .map(s -> new Seat(
                        new SeatCode(s.getSeatCode()),
                        s.getStatus(),
                        s.getReservedByBookingId(),
                        s.getTier(),
                        s.getPrice()))
                .toList();
        return SeatInventory.reconstitute(entity.getShowtimeId(), seats);
    }
}
